/**
 * 格内**小贴片**的统一尺与固定落位（唯一出处）
 *
 * 用户 2026-11-26：「统一格子里 HQ、设施、占领标记等小贴图的尺寸，每个东西有固定的放置位置」。
 *
 * ## 为什么要有这一层
 *   修前每个家族各写一套数值：设施 0.28R / HQ 0.24R / 占领标记 0.6R / 印刷工事 0.7R /
 *   通用标记 0.5R，角落也是各自 ±0.42 各算各的 ⇒ 同格并存时大小参差、位置相撞。
 *   现在统一成 **一枚尺寸 `HEX_CHIP_SIZE_RATIO`** ＋ **一张固定锚点表**：
 *
 *   | 槽位 | 谁 | 锚点（R 的倍数） |
 *   |---|---|---|
 *   | 左上 | 占领标记（5.0c） | (-0.42, -0.46) |
 *   | 上中 | 通用地图标记（13.3d 端头等） | (0, -0.52) |
 *   | 右上 | 印刷永久工事贴图（专规 1.3a） | (+0.42, -0.46) |
 *   | 左中 | HQ | (-0.52, 0) |
 *   | 左下 | 设施（SP / 运输点 / 空军基地 / 环形工事算子） | (-0.42, +0.46) |
 *   | 右下 | 建造标记（专规 3.5） | (+0.52, +0.46) |
 *
 * 同一槽位多枚（设施 / 建造标记）沿 `HEX_CHIP_SLOT_STEP` **向右**依次排开；
 * 格心留给算子堆叠与格号标注，任何贴片都不进格心。
 *
 * 例外两处，刻意不并入本表：
 *   · **堆叠枚数角标**（`drawStackBadge`）钉在**顶牌算子自己的右上角**，随算子走、不随格心走；
 *   · **扣兵力 / DG 状态贴图**（`STATUS_TEXTURE_SIZE_RATIO`）同理，贴在各自算子框内。
 *   这两类是"这枚算子的状态"，不是"这格的公共事实"。
 */

/** 小贴片的统一边长（R 的倍数）——比算子（约 1R）小，常显也不挡印值 */
export const HEX_CHIP_SIZE_RATIO = 0.28

/** 同槽位多枚时的排开步长（R 的倍数，向右；≥ 边长 ⇒ 相邻两枚留缝不叠） */
export const HEX_CHIP_SLOT_STEP = 0.3

/** 格内固定槽位（每样东西一个，互不挤占） */
export type HexChipKind =
  'control' | 'mapMarker' | 'printedHedgehog' | 'hq' | 'facility' | 'construction'

/** 每个槽位相对格心的锚点（单位＝外接圆半径 R；缩放时相对关系不变） */
export const HEX_CHIP_ANCHORS: Readonly<Record<HexChipKind, { x: number; y: number }>> = {
  control: { x: -0.42, y: -0.46 },
  mapMarker: { x: 0, y: -0.52 },
  printedHedgehog: { x: 0.42, y: -0.46 },
  hq: { x: -0.52, y: 0 },
  facility: { x: -0.42, y: 0.46 },
  construction: { x: 0.52, y: 0.46 },
}
